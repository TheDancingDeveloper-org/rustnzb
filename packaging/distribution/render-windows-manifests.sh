#!/bin/sh
# Render the Scoop and winget manifests for a rustnzb Windows release.
#
# Both manifests describe the same NSIS installer asset, so they are rendered
# from one checksum file in one pass. Nothing is published: the files land under
# packaging/scoop and packaging/winget for the operator to submit.
#
# usage: render-windows-manifests.sh TAG [--sums FILE] [--assets-dir DIR]
#                                       [--release-date YYYY-MM-DD] [--out DIR]
#
#   TAG           release tag, e.g. v1.5.0
#   --sums FILE   use a local SHA256SUMS-<tag>.txt instead of downloading it
#   --assets-dir  directory holding the installer asset, to verify it
#   --release-date  optional release date recorded in the winget installer
#   --out DIR     repository root to write under (default: this checkout)
#
# Every rendered value comes from the release's own SHA256SUMS file. A release
# that does not list the Windows installer, or an asset that does not match the
# listed hash, aborts before anything is written.
set -eu

repo=TheDancingDeveloper-org/rustnzb
homepage=https://rustnzb.dev
publisher=TheDancingDeveloper
package_id=$publisher.rustnzb

tag=${1:?usage: render-windows-manifests.sh TAG [--sums FILE] [--assets-dir DIR] [--out DIR]}
shift
case "$tag" in
    v[0-9]*.[0-9]*.[0-9]*) ;;
    *) echo "render-windows-manifests: tag must look like vX.Y.Z or vX.Y.Z-suffix" >&2; exit 2 ;;
esac
version=${tag#v}

sums=
assets_dir=
release_date=
out=
while [ $# -gt 0 ]; do
    case "$1" in
        --sums) sums=${2:?--sums needs a file}; shift 2 ;;
        --assets-dir) assets_dir=${2:?--assets-dir needs a directory}; shift 2 ;;
        --release-date) release_date=${2:?--release-date needs YYYY-MM-DD}; shift 2 ;;
        --out) out=${2:?--out needs a directory}; shift 2 ;;
        *) echo "render-windows-manifests: unknown argument: $1" >&2; exit 2 ;;
    esac
done

case "$release_date" in
    '') ;;
    [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]) ;;
    *) echo "render-windows-manifests: --release-date must be YYYY-MM-DD" >&2; exit 2 ;;
esac

script_dir=$(CDPATH="" cd -- "$(dirname -- "$0")" && pwd)
root=${out:-$(CDPATH="" cd -- "$script_dir/../.." && pwd)}
asset=rustnzb-$tag-windows-x86_64-setup.exe
url=https://github.com/$repo/releases/download/$tag/$asset

work=
tmp=
cleanup() { [ -z "$work" ] || rm -rf "$work"; [ -z "$tmp" ] || rm -f "$tmp"; }
trap cleanup EXIT

if [ -z "$sums" ]; then
    work=$(mktemp -d)
    curl -fsSL -o "$work/SHA256SUMS-$tag.txt" \
        "https://github.com/$repo/releases/download/$tag/SHA256SUMS-$tag.txt"
    sums=$work/SHA256SUMS-$tag.txt
fi
test -f "$sums" || { echo "render-windows-manifests: no such file: $sums" >&2; exit 1; }

expected=$(awk -v f="$asset" '$2 == f || $2 == "*" f { print tolower($1) }' "$sums")
test -n "$expected" || {
    echo "render-windows-manifests: $asset is not listed in $sums" >&2
    exit 1
}
case "$expected" in
    *[!0-9a-f]*) echo "render-windows-manifests: bad hash for $asset in $sums" >&2; exit 1 ;;
esac
[ ${#expected} -eq 64 ] || {
    echo "render-windows-manifests: hash for $asset is not 64 hex characters" >&2
    exit 1
}

if [ -n "$assets_dir" ]; then
    test -f "$assets_dir/$asset" || {
        echo "render-windows-manifests: $assets_dir/$asset is missing" >&2
        exit 1
    }
    actual=$(sha256sum "$assets_dir/$asset" | awk '{ print $1 }')
    [ "$actual" = "$expected" ] || {
        echo "render-windows-manifests: checksum mismatch for $asset" >&2
        echo "  expected $expected" >&2
        echo "  actual   $actual" >&2
        exit 1
    }
    echo "render-windows-manifests: verified $asset ($expected)"
fi

scoop_dir=$root/packaging/scoop/bucket
winget_root=$root/packaging/winget/manifests/t/$publisher/rustnzb
winget_dir=$winget_root/$version
mkdir -p "$scoop_dir" "$winget_dir"

upper_hash=$(printf '%s' "$expected" | tr 'a-f' 'A-F')
date_line=
[ -z "$release_date" ] || date_line="ReleaseDate: \"$release_date\""

tmp=$scoop_dir/rustnzb.json.tmp

cat >"$tmp" <<EOF
{
    "##": "Template kept in the rustnzb source repository; CI never publishes it. Regenerated by packaging/distribution/render-windows-manifests.sh.",
    "\$schema": "https://raw.githubusercontent.com/ScoopInstaller/Scoop/master/schema.json",
    "version": "$version",
    "description": "Usenet NZB downloader with a SABnzbd-compatible API and web UI.",
    "homepage": "$homepage",
    "license": "MIT",
    "architecture": {
        "64bit": {
            "url": "$url",
            "hash": "$expected"
        }
    },
    "pre_install": [
        "Expand-7zipArchive \"\$dir\\\\\$fname\" \"\$dir\"",
        "Remove-Item \"\$dir\\\\\$fname\""
    ],
    "bin": "rustnzb.exe",
    "shortcuts": [
        [
            "rustnzb.exe",
            "rustnzb"
        ]
    ],
    "notes": [
        "The release asset is an NSIS installer; this manifest extracts it instead of running it, so no registry entries or service are created.",
        "Pass --config <path> to pin the config file; without it rustnzb creates one in its default location on first start.",
        "The web UI listens on http://localhost:9090.",
        "Archive extraction needs 7-Zip on PATH: scoop install 7zip."
    ],
    "checkver": {
        "github": "https://github.com/$repo",
        "regex": "v([\\\\d.]+)\$"
    },
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "https://github.com/$repo/releases/download/v\$version/rustnzb-v\$version-windows-x86_64-setup.exe"
            }
        }
    }
}
EOF
mv "$tmp" "$scoop_dir/rustnzb.json"
tmp=

cat >"$winget_dir/$package_id.yaml" <<EOF
# Template kept in the rustnzb source repository; CI never submits it.
# Regenerated by packaging/distribution/render-windows-manifests.sh.
PackageIdentifier: $package_id
PackageVersion: $version
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.10.0
EOF

cat >"$winget_dir/$package_id.locale.en-US.yaml" <<EOF
# Template kept in the rustnzb source repository; CI never submits it.
PackageIdentifier: $package_id
PackageVersion: $version
PackageLocale: en-US
Publisher: $publisher
PublisherUrl: https://github.com/TheDancingDeveloper-org
PublisherSupportUrl: https://github.com/$repo/issues
PackageName: rustnzb
PackageUrl: $homepage
License: MIT
LicenseUrl: https://github.com/$repo/blob/main/LICENSE
ShortDescription: Usenet NZB downloader with a SABnzbd-compatible API and web UI
Moniker: rustnzb
Tags:
- usenet
- nzb
- sabnzbd
- downloader
Description: |-
  rustnzb downloads NZBs over pipelined TLS NNTP connections, decodes yEnc,
  verifies and repairs PAR2 sets, extracts archives, and exposes both a native
  REST API and a SABnzbd-compatible API for *arr applications and SAB clients.
ReleaseNotesUrl: https://github.com/$repo/releases/tag/$tag
ManifestType: locale
ManifestVersion: 1.10.0
EOF

cat >"$winget_dir/$package_id.installer.yaml" <<EOF
# Template kept in the rustnzb source repository; CI never submits it.
PackageIdentifier: $package_id
PackageVersion: $version
InstallerType: nullsoft
Scope: machine
UpgradeBehavior: install
Commands:
- rustnzb
FileExtensions:
- nzb
ElevationRequirement: elevatesSelf
$date_line
Installers:
- Architecture: x64
  InstallerUrl: $url
  InstallerSha256: $upper_hash
  AppsAndFeaturesEntries:
  - DisplayName: rustnzb $version
    Publisher: $publisher
    DisplayVersion: $version
ManifestType: installer
ManifestVersion: 1.10.0
EOF

printf 'render-windows-manifests: wrote Scoop and winget manifests for %s (sha256 %s)\n' \
    "$tag" "$expected"
